# ============================================
# SCRIPT 3: Carga del dataset y fusión de dudas
# ============================================
"""---

**Script 3 – Carga del dataset y fusión de etiquetas "duda"**

---

**Propósito**
Cargar el archivo Excel con los datos etiquetados y agrupar las diferentes categorías de dudas (`duda_no_atomica`, `duda_origen`, `duda_destino`, `duda`) en una única clase unificada llamada `duda_vaga`.

---

**¿Por qué es necesario?**
Tener demasiadas subcategorías de dudas con pocos ejemplos puede confundir al modelo. Al fusionarlas en una sola clase (`duda_vaga`), se reduce el número de clases totales a 5, se equilibra el dataset y el modelo puede aprender patrones generales de "ambigüedad".

---
"""

import pandas as pd
import re

print("="*60)
print("CARGANDO DATASET")
print("="*60)

ruta = '/content/drive/MyDrive/etiquetado_dudasclasificadas1.xlsx'
df = pd.read_excel(ruta, sheet_name='Muestra_Etiquetado')

print("Distribución original:")
print(df['Etiqueta'].value_counts())

mapeo_dudas = {
    'duda_no_atomica': 'duda_vaga',
    'duda_origen': 'duda_vaga',
    'duda_destino': 'duda_vaga',
    'duda': 'duda_vaga'
}
df['Etiqueta'] = df['Etiqueta'].replace(mapeo_dudas)

print("\nDistribución fusionada (5 clases):")
print(df['Etiqueta'].value_counts())


# ============================================
# SCRIPT 4: Marcado de entidades (E1 y E2)
# ============================================
"""---

**Script 4 – Marcado de entidades clínicas (E1 / E2) en el texto**

---

**Propósito**
Identificar y delimitar los nombres del fármaco origen (E1) y del fármaco destino (E2) dentro de cada oración, añadiendo etiquetas de texto (`[E1]` y `[E2]`).

---

**¿Por qué es necesario?**
Los modelos Transformer como BioBERT pueden perder el foco si la oración es larga. Al marcar explícitamente las entidades, le damos una pista contextual valiosísima al modelo, ayudándole a entender qué fármaco es el que interactúa con cuál. Es una técnica clave en la extracción de relaciones.

---
"""

print("\n" + "="*60)
print("MARCANDO ENTIDADES")
print("="*60)

def marcar_entidades(row):
    texto = str(row['Oracion_Interaccion'])
    origen = str(row['Farmaco_Origen'])
    destino = str(row['Farmaco_Destino'])

    patron_origen = re.compile(re.escape(origen), re.IGNORECASE)
    texto = patron_origen.sub(f"[E1] {origen} [/E1]", texto, count=1)

    patron_destino = re.compile(re.escape(destino), re.IGNORECASE)
    texto = patron_destino.sub(f"[E2] {destino} [/E2]", texto, count=1)

    return texto

df['Texto_Marcado'] = df.apply(marcar_entidades, axis=1)
print("Ejemplo:", df['Texto_Marcado'].iloc[0])


# ============================================
# SCRIPT 5: Preparación del dataset para Hugging Face
# ============================================
"""---

**Script 5 – Tokenización y adaptación del dataset para Transformers**

---

**Propósito**
Convertir los textos marcados y sus etiquetas en objetos `Dataset` de Hugging Face, listos para ser procesados por BioBERT.

---

**¿Por qué es necesario?**
Los modelos Transformer no entienden texto plano; necesitan que las palabras se conviertan en "tokens" numéricos (tokenización). Además, se requiere dividir los datos en entrenamiento (80%) y prueba (20%) manteniendo la proporción de las 5 clases (`stratify`).

---
"""

from sklearn.model_selection import train_test_split
from datasets import Dataset
from transformers import AutoTokenizer

label_map = {
    'effect': 0,
    'advise': 1,
    'mechanism': 2,
    'no_interaction': 3,
    'duda_vaga': 4
}
id2label = {v: k for k, v in label_map.items()}

df['label'] = df['Etiqueta'].map(label_map)

train_df, test_df = train_test_split(
    df, test_size=0.2, random_state=42, stratify=df['label']
)

print(f"Train: {len(train_df)} | Test: {len(test_df)}")

tokenizer = AutoTokenizer.from_pretrained("dmis-lab/biobert-v1.1")

def tokenize_function(examples):
    return tokenizer(
        examples['Texto_Marcado'],
        padding='max_length',
        truncation=True,
        max_length=128
    )

train_dataset = Dataset.from_pandas(train_df[['Texto_Marcado', 'label']])
test_dataset = Dataset.from_pandas(test_df[['Texto_Marcado', 'label']])

train_dataset = train_dataset.map(tokenize_function, batched=True)
test_dataset = test_dataset.map(tokenize_function, batched=True)

train_dataset = train_dataset.rename_column("label", "labels")
test_dataset = test_dataset.rename_column("label", "labels")

print("✅ Datasets preparados")


# ============================================
# SCRIPT 6: Carga del modelo base BioBERT
# ============================================
"""---

**Script 6 – Inicialización del modelo BioBERT**

---

**Propósito**
Cargar la arquitectura `BioBERT` preentrenada con una cabeza de clasificación personalizada para 5 clases.

---

**¿Por qué es necesario?**
Se carga el modelo base `dmis-lab/biobert-v1.1`, que ya "sabe" leer literatura biomédica, y se le añade una capa final (`SequenceClassification`) que se ajustará específicamente para nuestro problema de 5 etiquetas.

---
"""

print("\n" + "="*60)
print("CARGANDO BIOBERT")
print("="*60)

from transformers import AutoModelForSequenceClassification

model = AutoModelForSequenceClassification.from_pretrained(
    "dmis-lab/biobert-v1.1",
    num_labels=5,
    id2label=id2label,
    label2id=label_map
)

print("✅ BioBERT cargado")


# ============================================
# SCRIPT 7: Configuración del Trainer con Early Stopping
# ============================================
"""---

**Script 7 – Configuración del entrenamiento con parada temprana (Early Stopping)**

---

**Propósito**
Configurar los hiperparámetros de entrenamiento y añadir un mecanismo de "Early Stopping" para detener el entrenamiento si el modelo deja de mejorar.

---

**¿Por qué es necesario?**
En la versión anterior, el modelo entrenaba 3 épocas fijas. Aquí se sube el límite a 10 épocas, pero con `EarlyStoppingCallback(patience=2)`. Esto significa que si el F1 Macro no mejora después de 2 épocas, el entrenamiento se detiene automáticamente. Esto **previene el sobreajuste (overfitting)** y ahorra tiempo y recursos.

---
"""

print("\n" + "="*60)
print("CONFIGURANDO ENTRENAMIENTO CON EARLY STOPPING")
print("="*60)

from transformers import TrainingArguments, Trainer, EarlyStoppingCallback
from sklearn.metrics import f1_score
import numpy as np

def compute_metrics(eval_pred):
    predictions, labels = eval_pred
    predictions = np.argmax(predictions, axis=1)
    return {
        "f1_macro": f1_score(labels, predictions, average="macro"),
        "f1_weighted": f1_score(labels, predictions, average="weighted")
    }

training_args = TrainingArguments(
    output_dir="./biobert_ddi_v2",
    num_train_epochs=10,                 # ⭐ máximo alto
    per_device_train_batch_size=16,
    per_device_eval_batch_size=32,
    learning_rate=2e-5,
    warmup_steps=100,
    weight_decay=0.01,
    eval_strategy="epoch",
    save_strategy="epoch",
    load_best_model_at_end=True,
    metric_for_best_model="f1_macro",
    greater_is_better=True,
    report_to="none"
)

trainer = Trainer(
    model=model,
    args=training_args,
    train_dataset=train_dataset,
    eval_dataset=test_dataset,
    compute_metrics=compute_metrics,
    callbacks=[EarlyStoppingCallback(early_stopping_patience=2)]  # ⭐
)

print("✅ Trainer configurado")


# ============================================
# SCRIPT 8: Entrenamiento del modelo
# ============================================
"""---

**Script 8 – Entrenamiento del modelo (Fine-tuning)**

---

**Propósito**
Ejecutar el entrenamiento del modelo y evaluar su rendimiento final.

---

**¿Por qué es necesario?**
Aquí es donde el modelo ajusta sus pesos. Gracias al Early Stopping configurado en el paso anterior, esta celda podría tardar menos de 10 épocas si el modelo alcanza su punto óptimo de aprendizaje antes.

---
"""

print("\n" + "="*60)
print("ENTRENANDO (esto tarda ~20-25 min en GPU)")
print("="*60)

trainer.train()

results = trainer.evaluate()
print("\n" + "="*60)
print("RESULTADOS - BioBERT v2 (5 clases + Early Stopping)")
print("="*60)
print(f"F1 Macro:    {results['eval_f1_macro']:.4f}")
print(f"F1 Weighted: {results['eval_f1_weighted']:.4f}")


# ============================================
# SCRIPT 9: Reporte detallado por clase
# ============================================
"""---

**Script 9 – Generación de reporte y matriz de confusión**

---

**Propósito**
Evaluar el rendimiento del modelo desglosado por cada una de las 5 clases.

---

**¿Por qué es necesario?**
El F1 Macro general puede ocultar problemas. Ver la matriz de confusión y el reporte por clase nos permite saber si el modelo está confundiendo, por ejemplo, la clase `duda_vaga` con `no_interaction`.

---
"""

print("\n" + "="*60)
print("REPORTE POR CLASE")
print("="*60)

from sklearn.metrics import classification_report, confusion_matrix

predictions = trainer.predict(test_dataset)
y_pred = np.argmax(predictions.predictions, axis=1)
y_true = predictions.label_ids

nombres_clases = [id2label[i] for i in range(5)]
print(classification_report(y_true, y_pred, target_names=nombres_clases))

print("Matriz de confusión:")
cm = confusion_matrix(y_true, y_pred)
print(cm)
print(f"Labels: {nombres_clases}")


