"""**Script 4 – Parser de interacciones y extracción de pares desde "Información Combinada"**

---
**Propósito**

Extraer de manera estructurada los pares de interacciones fármaco-fármaco que se encuentran dentro del texto combinado (columna Información Combinada), separando cada interacción en sus componentes: fármaco origen, ID del fármaco destino, nombre del fármaco destino y la oración que describe la interacción.

---
**¿Por qué es necesario?**

La columna Información Combinada contiene el texto original del Excel y las interacciones del DrugBank en un solo bloque, pero en un formato no estructurado. Para poder utilizar estos datos en un modelo de NLP, es necesario desglosar cada interacción individual y convertirla en un registro independiente con sus campos bien definidos.

---
**Pasos que realiza:**

Definición del parser – Crea una función que recibe el texto combinado y el nombre del fármaco origen. Utiliza una expresión regular para identificar patrones como DBxxxxx (ID de DrugBank), seguido del nombre del fármaco destino y una oración que comienza con "The...". Cada coincidencia se convierte en un diccionario con cuatro campos: fármaco origen, ID destino, fármaco destino y oración de interacción.

Prueba sobre un ejemplo – Carga la hoja Analisis_Combinado, toma el primer fármaco de la lista y aplica el parser a su texto combinado. Muestra en pantalla cuántas interacciones se han encontrado y una vista previa de los primeros 10 pares extraídos.

---
**Utilidad en el proyecto**

Este script valida que el parser funciona correctamente sobre datos reales. Sirve como prueba de concepto antes de aplicarlo a todo el conjunto de datos. Demuestra que es posible desglosar automáticamente las interacciones a partir del texto combinado, lo que permitirá generar un dataset estructurado con pares de fármacos y sus oraciones de interacción para el entrenamiento del modelo de NLP.

---
"""

import pandas as pd
import re

# ==========================================
# 1. FUNCIÓN PARSER (EXPRESIÓN REGULAR)
# ==========================================
def parsear_interacciones_drugbank(texto_completo, farmaco_origen=""):
    if not isinstance(texto_completo, str) or "tsv: Sin interacciones" in texto_completo:
        return []

    # Expresión regular para separar: ID (DBxxxxx) + Nombre Droga 2 + Oración que inicia con 'The...'
    patron = r'(DB\d{5})([A-Za-z0-9\s\-]+?)(The\s+.+?\.)(?=DB\d{5}|$)'
    coincidencias = re.findall(patron, texto_completo)

    registros = []
    for db_id, droga_destino, texto_interaccion in coincidencias:
        registros.append({
            'Farmaco_Origen (E1)': farmaco_origen.strip(),
            'ID_Farmaco_Destino': db_id.strip(),
            'Farmaco_Destino (E2)': droga_destino.strip(),
            'Oracion_Interaccion': texto_interaccion.strip()
        })
    return registros

# ==========================================
# 2. CARGA DIRECTA DESDE DRIVE Y PRUEBA
# ==========================================
